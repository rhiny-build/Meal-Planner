// Playwright check against a running dev server (npm run dev, local Postgres, dev Claude key). Run: node scripts/next-week/e2e/3-phone-edit-old-list.cjs
// Needs RECEIPTS_ZIP (synthetic zip, see scripts/next-week/make-synthetic-zip.ts) for step 1. Screenshots go to docs/rehaul/logs/next-week-screens/.
const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })
  const p = await phone.newPage()
  p.on('pageerror', e => console.log('PAGEERROR', e.message))
  await p.goto('http://localhost:3000/shopping-list')
  await p.waitForSelector("text=Next week's list")
  await p.screenshot({ path: 'docs/rehaul/logs/next-week-screens/phone-tabs.png', clip: { x: 0, y: 0, width: 390, height: 300 } })
  await p.getByRole('tab', { name: 'Usual' }).click()
  await p.getByRole('button', { name: 'Edit Bananas Loose' }).click()
  await p.getByRole('textbox', { name: 'Item' }).fill('banana')
  await p.getByRole('combobox', { name: 'Aisle' }).selectOption('Bakery')
  await p.getByRole('button', { name: 'Save' }).click()
  await p.waitForTimeout(1500)
  console.log('bananas under Bakery:', await p.locator('div:has(> p:text("Bakery"))').first().innerText().then(t => t.includes('Bananas')))
  await p.getByRole('tab', { name: 'Need these?' }).click()
  await p.screenshot({ path: 'docs/rehaul/logs/next-week-screens/phone-need.png', fullPage: true })
  console.log('overflow:', await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth))
  await p.goto('http://localhost:3000/shopping-list?tab=list'); await p.waitForTimeout(800)
  console.log('old list reachable:', await p.getByRole('tab', { name: 'List' }).getAttribute('aria-selected'))
  await browser.close()
})().catch(e => { console.error(e); process.exit(1) })

// Playwright check against a running dev server (npm run dev, local Postgres, dev Claude key). Run: node scripts/next-week/e2e/2-next-week-page.cjs
// Needs RECEIPTS_ZIP (synthetic zip, see scripts/next-week/make-synthetic-zip.ts) for step 1. Screenshots go to docs/rehaul/logs/next-week-screens/.
const { chromium } = require('playwright')
;(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] })
  const page = await ctx.newPage()
  page.on('pageerror', e => console.log('PAGEERROR', e.message))
  await page.goto('http://localhost:3000/shopping-list')
  await page.waitForSelector('text=Next week\'s list')
  await page.screenshot({ path: 'docs/rehaul/logs/next-week-screens/desktop.png', fullPage: true })
  console.log('count:', await page.innerText('[data-testid=ticked-count]'))
  // toggle a usual item and a maybe item, reload, check kept
  const first = page.getByRole('checkbox').filter({ hasText: 'Milk' }).first()
  console.log('milk before:', await first.getAttribute('aria-checked'))
  await first.click()
  await page.waitForTimeout(600)
  await page.reload()
  await page.waitForSelector('text=Next week\'s list')
  console.log('milk after reload:', await page.getByRole('checkbox').filter({ hasText: 'Milk' }).first().getAttribute('aria-checked'))
  console.log('count:', await page.innerText('[data-testid=ticked-count]'))
  await page.getByRole('button', { name: /Copy for Sainsbury/ }).click()
  await page.waitForTimeout(300)
  const clip = await page.evaluate(() => navigator.clipboard.readText())
  console.log('CLIPBOARD lines:', clip.split('\n').length); console.log(clip.split('\n').slice(0, 6).join(' / '))
  // old list still reachable
  await page.getByRole('tab', { name: "This Week's Meals" }).click()
  await page.waitForTimeout(800)
  console.log('old tab url:', page.url())
  // phone
  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true })
  const p2 = await phone.newPage()
  await p2.goto('http://localhost:3000/shopping-list')
  await p2.waitForSelector('text=Next week\'s list')
  await p2.screenshot({ path: 'docs/rehaul/logs/next-week-screens/phone-meals.png', fullPage: true })
  await p2.getByRole('tab', { name: 'Usual' }).click(); await p2.screenshot({ path: 'docs/rehaul/logs/next-week-screens/phone-usual.png', fullPage: true })
  await p2.getByRole('tab', { name: 'Need these?' }).click(); await p2.screenshot({ path: 'docs/rehaul/logs/next-week-screens/phone-need.png', fullPage: true })
  console.log('phone overflow:', await p2.evaluate(() => document.documentElement.scrollWidth > window.innerWidth))
  await browser.close()
})().catch(e => { console.error(e); process.exit(1) })
